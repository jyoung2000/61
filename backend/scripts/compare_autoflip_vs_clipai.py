#!/usr/bin/env python3
"""Week 3 — real-content comparison harness: MediaPipe AutoFlip vs ClipAI.

For every clip in ``tests/real_content/manifest.json``:

  1. Load the cached AutoFlip JSON timeline from
     ``tests/autoflip_reference_outputs/<slug>.json`` (generated by
     ``reference/autoflip/run_one.sh`` on the one-time Docker build).
  2. Build a ClipAI timeline in the same JSON shape — via the
     ``export_autoflip_compatible`` translator over a cached
     extraction (see below), or skipped with a note when the
     pipeline can't be invoked in the current environment.
  3. Optionally load a human ground-truth sidecar from
     ``tests/real_content/ground_truth/<slug>.json``.
  4. Score every available timeline with
     ``autoflip_parity_metrics.cut_to_hold_ratio`` plus the acceleration
     / jerk / overlap metrics.
  5. Emit a per-content-type markdown rollup to
     ``docs/week3_real_content_results.md`` and a raw JSON dump to
     ``/tmp/week3_results.json`` (or wherever ``--json-out`` points).

Usage:

    python -m backend.scripts.compare_autoflip_vs_clipai \\
        --manifest tests/real_content/manifest.json \\
        --autoflip-outputs tests/autoflip_reference_outputs/ \\
        --output docs/week3_real_content_results.md \\
        --json-out /tmp/week3_results.json

Optional flags:

    --filter "panel_*"         Only score clips whose slug matches the glob
    --clipai-only              Skip AutoFlip load (useful before cache
                               regeneration)
    --dry-run                  Enumerate clips + skip the ClipAI pipeline
                               call (fast iteration on the scoring layer)

Design notes:

  - The harness NEVER invokes the Docker MediaPipe runner directly.
    That's expensive and environment-dependent; the cached JSON is
    the supported comparison input. A missing cache file is a
    reported "skipped" row, not a failure.

  - The ClipAI pipeline invocation goes through
    ``run_clipai_on_clip(clip, video_path, cache_dir=…)`` which
    runs the full extraction stack (shots → dense faces → face
    registry → transcript → active speaker → content profile →
    anime anchors → reframe segments) against the resolved video
    path. The extracted features are cached by sha256 under
    ``$CLIPAI_REAL_CONTENT_CACHE/extractions/<sha>/`` so a second
    run against the same clip short-circuits to the cached segment
    list. When the manifest's video is missing on disk the clip is
    reported as ``clipai_skipped``; when ``--dry-run`` is passed the
    helper falls back to a synthetic one-frame-per-source-frame
    timeline for scoring-layer iteration.
"""
