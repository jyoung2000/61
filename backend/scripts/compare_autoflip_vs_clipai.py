def _derive_crop_centers_pct(events: list[dict]) -> list[float]:
    """Per-event crop_cx in percent (0-100) for the parity metrics."""
    return [float(e.get("crop_cx", 0.5)) * 100.0 for e in events]


def score_timeline(events: list[dict]) -> dict[str, Any]:
    """Run every applicable parity metric over an AutoFlip-shape
    event list.

    Returns a dict ready to paste into the markdown rollup.
    """
    from backend.services.autoflip_parity_metrics import (
        cut_to_hold_ratio,
        max_acceleration,
        max_jerk,
        overlap_count,
    )

    if not events:
        return {
            "n_segments": 0,
            "note": "empty event list",
        }

    crop_centers = _derive_crop_centers_pct(events)
    hold = cut_to_hold_ratio(events)

    # overlap_count consumes (start, end) spans; derive from the
    # scene_change flag distribution.
    segment_starts = [float(e["t"]) for e in events if e.get("scene_change")]
    if not segment_starts:
        segment_starts = [float(events[0]["t"])]
    segment_ends = segment_starts[1:] + [float(events[-1]["t"])]
    spans = list(zip(segment_starts, segment_ends))

    return {
        "n_segments": hold.get("n_segments", 0),
        "median_hold_sec": hold.get("median_hold_sec"),
        "p25": hold.get("p25"),
        "p75": hold.get("p75"),
        "p95": hold.get("p95"),
        "segments_under_1s_rate": hold.get("segments_under_1s_rate"),
        "segments_over_8s_rate": hold.get("segments_over_8s_rate"),
        "max_acceleration": max_acceleration(crop_centers),
        "max_jerk": max_jerk(crop_centers),
        "overlap_count": overlap_count(spans),
    }


def verdict_for(metrics: dict[str, Any], zone: Optional[dict[str, float]]) -> str:
    """Return PASS / MARGINAL / MISS / UNKNOWN for a (clip, tool) pair."""
    if not metrics or metrics.get("n_segments", 0) == 0:
        return "UNKNOWN"
    if zone is None:
        return "UNKNOWN"
    median = metrics.get("median_hold_sec")
    under = metrics.get("segments_under_1s_rate")
    if median is None or under is None:
        return "UNKNOWN"
    in_median = zone["median_hold_min"] <= median <= zone["median_hold_max"]
    under_ok = under <= zone["under_1s_max"]
    if in_median and under_ok:
        return "PASS"
    if in_median or under_ok:
        return "MARGINAL"
    return "MISS"


